-- Puts the three portal tables back exactly as they were before the 2026-11-01 renumbering.
-- Needs a TMapSvr restart afterwards. Keeps the backup tables; drop them by hand if you are sure.
SET NOCOUNT ON; SET XACT_ABORT ON;
IF OBJECT_ID('TPORTALCHART_bak_20261101') IS NULL THROW 50000,'No backup tables in this database',1;
BEGIN TRAN;
DELETE TPORTALCHART; INSERT TPORTALCHART SELECT * FROM TPORTALCHART_bak_20261101;
DELETE TDESTINATIONCHART; INSERT TDESTINATIONCHART SELECT * FROM TDESTINATIONCHART_bak_20261101;
DELETE TNPCITEMCHART; INSERT TNPCITEMCHART SELECT * FROM TNPCITEMCHART_bak_20261101;
COMMIT;
PRINT 'Restored '+DB_NAME();
