-- Season reset, 2026-11-06: deletes every account, character and anything tied to them.
-- Run with every server stopped, after backing up both databases:
--   sqlcmd -S "localhost\FOURSTORY" -E -C -b -i apply.sql
--
-- Uses DELETE, not TRUNCATE, so the ID counters keep counting up. Old IDs left in the
-- tables kept below (castle and territory owners, TMANAGER) can then never match a new
-- character or guild.
--
-- Kept on purpose:
--   TGROUP, TSERVER, TCHANNEL...  server and database configuration
--   TMANAGER, TMANAGERLOG         GM tool logins and their log, not game accounts
--   TTAXTABLE, TKEEPINGNAME, IPBLACKLIST_game, every *CHART table
--
-- Nobody can log in afterwards until accounts are added to TACCOUNT_PW and TUSERINFOTABLE (bAgreement = 1).
SET NOCOUNT ON;
SET XACT_ABORT ON;
GO

USE TGLOBAL_GSP;
GO
BEGIN TRAN;
DECLARE @t TABLE (n INT IDENTITY, name SYSNAME);
INSERT @t (name) VALUES
 ('TACCOUNT'),('TACCOUNT_PW'),('TUSERINFOTABLE'),('TSECURECODE'),('TTESTLOGINUSER'),
 ('TCURRENTUSER'),('TALLCHARTABLE'),('TALLCHARTABLE_TRIGGER'),('TALLRANKTABLE'),('TALLRANKGUILDTABLE'),('TALLLOCALTABLE'),
 ('TCASHITEMBUYTABLE'),('TCASHITEMCABINETTABLE'),('TCASHITEMCABINETTABLE_PW'),('TCASHITEMCABINETTABLE_temp'),
 ('TCASHTESTTABLE'),('TTEMPCASHITEM'),('TUNIFYCASHITEM'),('TUNIFYPOSTITEMTABLE'),('TDURINGITEMTABLE'),('TTEMPDURINGITEMTABLE'),
 ('TLOG'),('USERIPLOG'),('TPCBANGPLAYTABLE'),('TPCBANGMASTERTABLE'),('TRESERVEDNAME'),
 ('TUSERPROTECTED'),('TUSERPROTECTED_old'),('TUSERATTENDTABLE'),('TSMSTABLE'),
 ('TempEvent'),('TEMPUSERID'),('TEVENTGIVEERROR'),('TEVENTHORSE'),('ttemplevel'),('ttempuser');
DECLARE @i INT = 1, @name SYSNAME, @sql NVARCHAR(400);
WHILE @i <= (SELECT MAX(n) FROM @t)
BEGIN
  SELECT @name = name FROM @t WHERE n = @i;
  SET @sql = N'DELETE FROM dbo.' + QUOTENAME(@name) + N'; PRINT ''' + @name + N': '' + CAST(@@ROWCOUNT AS VARCHAR) + '' deleted'';';
  EXEC (@sql);
  SET @i += 1;
END
-- The TALLCHARTABLE delete trigger writes into TALLCHARTABLE_TRIGGER, so empty it last.
DELETE FROM dbo.TALLCHARTABLE_TRIGGER;
COMMIT;
PRINT 'TGLOBAL_GSP done';
GO

